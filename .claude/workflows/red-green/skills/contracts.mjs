// Property contracts: reads the `contract: <id>: <statement>` markers in the tracked files under the working directory,
// as text in any language. A marker is a line holding only an optional comment opener (// # -- ; % /* * <!-- (*), then
// `contract:`; a closer (*/ --> *)) at its end is dropped. An id is dot-separated segments of letters, digits, _ and -;
// contracts are grouped by its first segment. A statement is 255 characters at most.
//
// doc writes the contract doc to <path>. Exit 0 done; 1 an over-limit statement, a duplicate id or a malformed marker,
// nothing written (stderr names each); 2 it could not run. With --check it writes nothing and also exits 1 when <path>
// differs from what it would write.
//
//     node contracts.mjs doc <path> [--check]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname } from 'node:path'
import { parseArgs } from 'node:util'

const die = why => { process.stderr.write(`contracts: ${why}\n`); process.exit(2) }
const LIMIT = 255
const MARKER = /^\s*(?:\/\/+|#+|--|;+|%+|\/\*+|\*|<!--|\(\*)?\s*contract:(.*)$/
const CONTRACT = /^\s*([\w-]+(?:\.[\w-]+)*):\s+(.*?)\s*(?:\*\/|-->|\*\))?\s*$/
const DOMAIN = /^\s*(?:\/\/+|#+|--|;+|%+|\/\*+|\*|<!--|\(\*)?\s*domain:(.*)$/

// Every marker in the tracked files: {contracts: [{id, statement, file, line, domain}], problems: [string]}. `domain` is
// the raw text of a `domain:` marker on the next line, or null.
const scan = () => {
  const contracts = [], problems = []
  const files = execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8', maxBuffer: 1 << 28 }).split('\0').filter(Boolean)
  for (const file of files) {
    let text
    try { text = readFileSync(file, 'utf8') } catch { continue } // deleted in the tree, or a submodule
    if (text.includes('\0')) continue
    const lines = text.split(/\r?\n/)
    lines.forEach((l, i) => {
      const m = MARKER.exec(l)
      if (!m) return
      const where = `${file}:${i + 1}`
      const c = CONTRACT.exec(m[1])
      if (!c || !c[2]) return problems.push(`${where}: malformed marker, want contract: <id>: <statement>`)
      const [, id, statement] = c
      if ([...statement].length > LIMIT) problems.push(`${where}: ${id}: statement is ${[...statement].length} characters, over ${LIMIT}`)
      const twin = contracts.find(x => x.id === id)
      if (twin) problems.push(`${where}: ${id}: duplicate id, also at ${twin.file}:${twin.line}`)
      contracts.push({ id, statement, file, line: i + 1, domain: DOMAIN.exec(lines[i + 1] ?? '')?.[1].trim() ?? null })
    })
  }
  return { contracts, problems }
}

const render = contracts => {
  const out = ['# Property contracts', '', 'Generated by contracts.mjs doc from the markers in tracked files; do not edit.']
  let group
  for (const c of [...contracts].sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0)) {
    const g = c.id.split('.')[0]
    if (g !== group) out.push('', `## ${(group = g)}`, '')
    out.push(`- \`${c.id}\`: ${c.statement} (${c.file})`)
  }
  return out.join('\n') + '\n'
}

let o
try { o = parseArgs({ allowPositionals: true, options: { check: { type: 'boolean' } } }) } catch (e) { die(e.message) }
const [cmd, path, ...rest] = o.positionals
if (cmd !== 'doc' || !path || rest.length) die('usage: contracts.mjs doc <path> [--check]')
let found
try { found = scan() } catch (e) { die(e.message) }
const { contracts, problems } = found
const text = render(contracts)
if (o.values.check) {
  let old = null
  try { old = readFileSync(path, 'utf8') } catch {}
  if (old !== text) problems.push(`${path}: ${old === null ? 'missing' : 'stale'}, run contracts.mjs doc ${path}`)
}
if (problems.length) { process.stderr.write(problems.join('\n') + '\n'); process.exit(1) }
if (!o.values.check) {
  try { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text) } catch (e) { die(e.message) }
}
